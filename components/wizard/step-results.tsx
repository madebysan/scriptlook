type TabKey = (typeof TABS)[number]["key"];

type StepResultsProps = {
  documents: DocumentResult[];
  deliverables: readonly DeliverableId[];
  jsonData?: string;
  onJsonDataChange?: (newJsonData: string) => void;
  onStartOver: () => void;
  onDocumentUpdate?: (slug: string, newContent: string) => void;
  storyboardImages: Record<number, SavedImage>;
  onStoryboardImagesChange: (images: Record<number, SavedImage>) => void;
  promptOverrides: Record<number, string>;
  onPromptOverridesChange: (overrides: Record<number, string>) => void;
  posterImages: Record<number, SavedImage>;
  onPosterImagesChange: (images: Record<number, SavedImage>) => void;
  portraits: Record<string, SavedImage>;
  onPortraitsChange: (portraits: Record<string, SavedImage>) => void;
  propImages: Record<string, SavedImage>;
  onPropImagesChange: (images: Record<string, SavedImage>) => void;
  locationImages: Record<string, SavedImage>;
  onLocationImagesChange: (images: Record<string, SavedImage>) => void;
  disabledItems: Record<string, boolean>;
  onDisabledItemsChange: (items: Record<string, boolean>) => void;
};

export function StepResults({
  documents,
  deliverables,
  jsonData,
  onJsonDataChange,
  onStartOver,
  onDocumentUpdate,
  storyboardImages,
  onStoryboardImagesChange,
  promptOverrides,
  onPromptOverridesChange,
  posterImages,
  onPosterImagesChange,
  portraits,
  onPortraitsChange,
  propImages,
  onPropImagesChange,
  locationImages,
  onLocationImagesChange,
  disabledItems,
  onDisabledItemsChange,
}: StepResultsProps) {
  const [activeTab, setActiveTab] = useState<TabKey>("overview");
  const visibleTabs = useMemo(() => {
    const selectedSections = new Set(getReportSections(deliverables));
    return TABS.filter((tab) => selectedSections.has(tab.key));
  }, [deliverables]);
  const resolvedActiveTab = visibleTabs.some((tab) => tab.key === activeTab)
    ? activeTab
    : visibleTabs[0]?.key;
  const activeTabIndex = visibleTabs.findIndex((tab) => tab.key === resolvedActiveTab);
  const previousTab = activeTabIndex > 0 ? visibleTabs[activeTabIndex - 1] : undefined;
  const nextTab = activeTabIndex < visibleTabs.length - 1 ? visibleTabs[activeTabIndex + 1] : undefined;

  const navigateToTab = useCallback((tab: TabKey) => {
    setActiveTab(tab);
    window.requestAnimationFrame(() => {
      const behavior: ScrollBehavior = window.matchMedia("(prefers-reduced-motion: reduce)").matches
        ? "auto"
        : "smooth";
      const activeButton = document.querySelector<HTMLElement>(
        `[data-report-tab="${tab}"]`
      );
      activeButton?.scrollIntoView({
        block: "nearest",
        inline: "center",
        behavior,
      });
      window.scrollTo({ top: 0, behavior });
    });
  }, []);

  const toSectionNavItem = (
    tab: (typeof TABS)[number] | undefined
  ): ReportSectionNavItem | undefined => {
    if (!tab) return undefined;
    const tabIndex = visibleTabs.findIndex((item) => item.key === tab.key);
    return {
      index: String(tabIndex + 1).padStart(2, "0"),
      label: tab.label,
      onClick: () => navigateToTab(tab.key),
    };
  };

  // Keyboard shortcuts for tab navigation:
  //   ⌥/Alt + ←/→  → previous / next tab
  //   ⌥/Alt + 1..8 → jump to tab N
  // Modifier required so single arrow keys keep working in textareas/inputs
  // and don't fight inline-edit affordances.
  useEffect(() => {
    function onKey(e: KeyboardEvent) {
      if (!e.altKey) return;
      const target = e.target as HTMLElement | null;
      // Bail if we're inside any editable surface — the user is typing.
      if (target && (target.tagName === "INPUT" || target.tagName === "TEXTAREA" || target.isContentEditable)) {
        return;
      }
      const idx = visibleTabs.findIndex((t) => t.key === resolvedActiveTab);
      if (e.key === "ArrowRight") {
        e.preventDefault();
        const next = visibleTabs[(idx + 1) % visibleTabs.length];
        navigateToTab(next.key);
        return;
      }
      if (e.key === "ArrowLeft") {
        e.preventDefault();
        const prev = visibleTabs[(idx - 1 + visibleTabs.length) % visibleTabs.length];
        navigateToTab(prev.key);
        return;
      }
      const numKey = Number(e.key);
      if (Number.isInteger(numKey) && numKey >= 1 && numKey <= visibleTabs.length) {
        e.preventDefault();
        navigateToTab(visibleTabs[numKey - 1].key);
      }
    }
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [navigateToTab, resolvedActiveTab, visibleTabs]);

  const getDoc = (slug: string) => documents.find((d) => d.slug === slug);
  const getDocContent = (slug: string): string | null => {
    const doc = getDoc(slug);
    return doc?.status === "done" ? doc.content : null;
  };

  const failedDocs = documents.filter((d) => d.status === "error");

  const overviewContent = getDocContent("overview");
  const moodContent = getDocContent("mood-and-tone");
  const sceneContent = getDocContent("scene-breakdown");
  const storyboardContent = getDocContent("storyboard-prompts");
  const posterContent = getDocContent("poster-concepts");

  if (!jsonData) {
    return (
      <div className="form-sheet p-8 text-center sm:p-12">
        <p className="text-muted-foreground">
          No screenplay data is loaded. Paste the JSON again.
        </p>
        <Button className="mt-4" onClick={onStartOver}>
          Start Over
        </Button>
      </div>
    );
  }

  return (
    <div className="space-y-5">
      {failedDocs.length > 0 && (
        <div className="border-2 border-destructive bg-[var(--paper-sheet)] p-4">
          <p className="text-sm font-medium text-destructive mb-2">
            Some report sections failed:
          </p>
          <ul className="space-y-1">
            {failedDocs.map((doc) => (
              <li key={doc.slug} className="text-sm text-destructive/80">
                {doc.name}: {doc.error}
              </li>
            ))}
          </ul>
        </div>
      )}

      <div className="form-sheet report-surface grid min-h-[600px] overflow-hidden lg:grid-cols-[230px_minmax(0,1fr)] xl:grid-cols-[250px_minmax(0,1fr)]">
        <aside className="sticky top-0 z-40 min-w-0 overflow-hidden border-b-2 border-foreground bg-[var(--paper-sheet)] lg:static lg:z-auto lg:border-b-0 lg:border-r-2 lg:self-start">
          <div className="min-w-0 overflow-hidden">
            <div className="hidden border-b-2 border-foreground px-4 py-5 lg:block">
              <div className="form-sec-head text-[16px] text-foreground">
                Deck Index
              </div>
              <p className="mt-1.5 font-mono text-[10px] uppercase tracking-[0.08em] text-foreground/60">
                Department working copy
              </p>
            </div>

            <nav className="flex w-full min-w-0 overflow-x-auto lg:block lg:overflow-visible" aria-label="Report sections">
              {visibleTabs.map((tab, index) => (
                <ReportNavButton
                  key={tab.key}
                  active={tab.key === activeTab}
                  icon={tab.icon}
                  index={String(index + 1).padStart(2, "0")}
                  label={tab.label}
                  role={tab.role}
                  tabKey={tab.key}
                  onClick={() => navigateToTab(tab.key)}
                />
              ))}
            </nav>
          </div>
        </aside>

        <section className="min-w-0 overflow-hidden bg-[var(--paper-sheet)]">
          <div className="border-b border-foreground/35 px-5 py-3 sm:px-7 lg:px-9">
            <div className="flex items-center justify-between gap-4 font-mono text-[9px] font-bold uppercase tracking-[0.12em] text-foreground/60">
              <span>Scriptlook / Film Vision Deck</span>
              <span>Working copy / {String(activeTabIndex + 1).padStart(2, "0")}</span>
            </div>
          </div>
          <div className="report-motion-content px-5 py-7 sm:px-7 sm:py-9 lg:px-9 lg:py-10">
            {resolvedActiveTab === "overview" && (
              overviewContent ? (
                <OverviewViewer
                  content={overviewContent}
                  jsonData={jsonData}
                  onContentUpdate={
                    onDocumentUpdate
                      ? (c) => onDocumentUpdate("overview", c)
                      : undefined
                  }
                  posterContent={posterContent}
                  posterImages={posterImages}
                  onNavigateToPosters={() => navigateToTab("posters")}
                />
              ) : (
                <GenerationPending label="Overview" />
              )
            )}

            {resolvedActiveTab === "mood-and-tone" && (
              moodContent ? (
                <MoodAndToneViewer
                  content={moodContent}
                  jsonData={jsonData}
                  onContentUpdate={
                    onDocumentUpdate
                      ? (c) => onDocumentUpdate("mood-and-tone", c)
                      : undefined
                  }
                />
              ) : (
                <GenerationPending label="Mood & Tone" />
              )
            )}

            {resolvedActiveTab === "scenes" && (
              sceneContent ? (
                <SceneBreakdownViewer
                  content={sceneContent}
                  jsonData={jsonData}
                  onContentChange={
                    onDocumentUpdate
                      ? (c) => onDocumentUpdate("scene-breakdown", c)
                      : undefined
                  }
                  storyboardContent={storyboardContent}
                  storyboardImages={storyboardImages}
                  onStoryboardImagesChange={onStoryboardImagesChange}
                  promptOverrides={promptOverrides}
                  onPromptOverridesChange={onPromptOverridesChange}
                />
              ) : (
                <GenerationPending label="Scenes" />
              )
            )}

            {resolvedActiveTab === "locations" && (
              <LocationsViewer
                jsonData={jsonData}
                locationImages={locationImages}
                onLocationImagesChange={onLocationImagesChange}
              />
            )}

            {resolvedActiveTab === "cast-and-crew" && (
              <CastAndCrewViewer
                jsonData={jsonData}
                onJsonDataChange={onJsonDataChange}
                portraits={portraits}
                onPortraitsChange={onPortraitsChange}
                disabledItems={disabledItems}
                onDisabledItemsChange={onDisabledItemsChange}
              />
            )}

            {resolvedActiveTab === "production" && (
              <ProductionViewer
                jsonData={jsonData}
                propImages={propImages}
                onPropImagesChange={onPropImagesChange}
              />
            )}

            {resolvedActiveTab === "identity" && (
              <IdentityViewer
                jsonData={jsonData}
                moodContent={moodContent}
                onMoodContentUpdate={
                  onDocumentUpdate
                    ? (c) => onDocumentUpdate("mood-and-tone", c)
                    : undefined
                }
              />
            )}

            {resolvedActiveTab === "posters" && (
              <PostersViewer
                posterContent={posterContent}
                posterImages={posterImages}
                onPosterImagesChange={onPosterImagesChange}
              />
            )}

            {resolvedActiveTab === "breakdown" && (
              <BreakdownViewer jsonData={jsonData} />
            )}

            {resolvedActiveTab === "schedule" && (
              <ScheduleViewer jsonData={jsonData} />
            )}

            {resolvedActiveTab === "shoot-plan" && (
              <ShootPlanViewer jsonData={jsonData} />
            )}

            {resolvedActiveTab === "shoot-brief" && (
              <ShootBriefViewer
                jsonData={jsonData}
                overviewContent={overviewContent}
              />
            )}

            <ReportSectionNav
              previous={toSectionNavItem(previousTab)}
              next={toSectionNavItem(nextTab)}
            />
          </div>
        </section>
      </div>
    </div>
  );
}

function ReportNavButton({
  active,
  icon: Icon,
  index,
  label,
  role,
  tabKey,
  onClick,
}: {
  active: boolean;
  icon: LucideIcon;
  index: string;
  label: string;
  role: string;
  tabKey: TabKey;
  onClick: () => void;
}) {
  return (
    <button
      type="button"
      data-report-tab={tabKey}
      onClick={onClick}
      className={`group grid min-w-[154px] grid-cols-[28px_minmax(0,1fr)] items-center gap-2 border-r border-foreground/35 px-3 py-3 text-left transition-colors sm:min-w-[176px] lg:w-full lg:min-w-0 lg:grid-cols-[28px_1fr_auto] lg:gap-3 lg:border-b lg:border-r-0 ${
        active
          ? "bg-[var(--paper-highlight)] text-foreground"
          : "bg-transparent text-foreground/58 hover:bg-[rgba(255,227,77,0.18)] hover:text-foreground"
      }`}
    >
      <span
        className={`flex h-7 w-7 items-center justify-center border transition-colors ${
          active
            ? "border-foreground bg-foreground text-[var(--paper-sheet)]"
            : "border-foreground/35 bg-transparent text-foreground/65 group-hover:border-foreground group-hover:text-foreground"
        }`}
      >
        <Icon size={13} />
      </span>
      <span className="min-w-0">
        <span className="block truncate font-mono text-[11px] font-bold uppercase tracking-[0.04em]">
          {label}
        </span>
        <span className="mt-0.5 hidden truncate font-mono text-[9px] uppercase tracking-[0.06em] opacity-65 lg:block">
          {role}
        </span>
      </span>
      <span className="hidden font-mono text-[9px] font-bold uppercase tracking-[0.08em] opacity-55 lg:block">
        {index}
      </span>
    </button>
  );
}

function GenerationPending({ label }: { label: string }) {
  return (
    <div className="report-motion-status flex flex-col items-center justify-center gap-3 py-12 text-center text-sm text-muted-foreground">
      <span className="report-loading-dot h-1.5 w-1.5 rounded-full bg-muted-foreground/70" />
      <span>{label} is still waiting on generation.</span>
    </div>
  );
}
